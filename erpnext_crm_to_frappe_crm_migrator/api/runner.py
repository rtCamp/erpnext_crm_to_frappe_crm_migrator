# Explicit overrides for the source → target parentfield mapping inside
# _reanchor_shared_children. Use when the source has an extra Table
# field (e.g. a custom_ duplicate) that should be merged into the
# canonical CRM target field instead of being skipped for lack of a
# same-name match. Keyed by (source_doctype, source_field) → target_field.
SHARED_CHILD_FIELD_MERGES: dict[tuple[str, str], str] = {
	# (Currently empty.) Populate when a source has an extra Table field
	# whose child doctype IS the same as the target's canonical Table,
	# and the rows should be folded into it rather than re-anchored
	# under a different field name. When the source/target child
	# doctypes differ (e.g. CRM Stage Change Log vs CRM Status Change
	# Log), use a `api/reshape.py` function instead — see
	# `reshape_opportunity_stage_logs`.
}


def _reanchor_shared_children(
	source_doctype: str,
	target_doctype: str,
	target_meta,
) -> int:
	"""Rewrite parenttype/parentfield on child rows whose child doctype is
	identical on both source and target meta.

	Discovery is via meta inspection — we don't read the locked field
	map for this. Table fields are deliberately hidden from the diff
	UI (they aren't column-mapped); shared-schema Tables still need
	re-anchoring, so we walk source meta and match every Table field
	whose name + options align with a Table on target meta. Schema-
	reshape children (where the child doctype itself changes) live in
	`api/reshape.py` and never enter this loop.

	`SHARED_CHILD_FIELD_MERGES` overrides the default same-name match
	for cases where a source has an extra Table field that should
	merge into the canonical target field (e.g.
	Opportunity.custom_status_change_log → CRM Deal.status_change_log).

	Returns the total number of child rows updated across all eligible
	child doctypes.
	"""
	source_meta = frappe.get_meta(source_doctype)
	total = 0
	seen: set[tuple[str, str]] = set()

	for src_df in source_meta.fields:
		if src_df.fieldtype not in ("Table", "Table MultiSelect"):
			continue
		if not src_df.options:
			continue
		# Decide which target field this source field re-anchors to:
		# explicit merge override first, else same-name fallback.
		merge_target = SHARED_CHILD_FIELD_MERGES.get((source_doctype, src_df.fieldname))
		tgt_fieldname = merge_target or src_df.fieldname
		tgt_df = target_meta.get_field(tgt_fieldname)
		if tgt_df is None or tgt_df.fieldtype != src_df.fieldtype:
			continue
		if (tgt_df.options or "") != (src_df.options or ""):
			# different child doctype → cross-table reshape, see api/reshape.py
			continue
		child_dt = src_df.options
		src_field = src_df.fieldname
		tgt_field = tgt_fieldname

		key = (child_dt, src_field)
		if key in seen:
			continue
		seen.add(key)

		# Count rows that still need re-anchoring BEFORE the UPDATE — that
		# count IS the number we'll be moving. Re-runs see 0 here because
		# the previous run already moved them all to the target parenttype.
		to_move = frappe.db.count(
			child_dt,
			filters={
				"parenttype": source_doctype,
				"parentfield": src_field,
			},
		)
		if to_move:
			child_tbl = frappe.qb.DocType(child_dt)
			(
				frappe.qb.update(child_tbl)
				.set(child_tbl.parenttype, target_doctype)
				.set(child_tbl.parentfield, tgt_field)
				.where((child_tbl.parenttype == source_doctype) & (child_tbl.parentfield == src_field))
				.run()
			)
			total += int(to_move)

	return total


# ---------------------------------------------------------------------------
# pre-flight: verify upstream lookups exist before migrating a parent
# ---------------------------------------------------------------------------

# Each parent maps to the upstream lookup target doctypes whose Link values
# may appear on its rows. Computed from the registry: for every parent's
# Link field whose target options is one of our migration target lookup
# doctypes, that target needs to be populated before this parent runs.
_PARENT_DEPENDENCIES = {
	"Lead": ["CRM Industry", "CRM Territory", "CRM Lead Source"],
	"Opportunity": [
		"CRM Industry",
		"CRM Territory",
		"CRM Lead Source",
		"CRM Lost Reason",
		"CRM Organization",  # party_name → Prospect → CRM Organization
	],
	"Prospect": ["CRM Industry", "CRM Territory"],
	# Self-references aren't pre-checked — the bulk_insert handles the same
	# table fine regardless of order, and Frappe Link fields aren't FK-enforced.
	"Territory": [],
	"Item": [],
	"Industry Type": [],
	"UTM Source": [],
	"Opportunity Lost Reason": [],
}


def _preflight_link_check(source_doctype: str) -> str | None:
	"""Return an explanatory string if the parent can't run yet, else None.

	A parent step is blocked if any of its upstream CRM lookup tables is
	empty when the source has Link values pointing into the corresponding
	source-side lookup. The check is deliberately coarse — empty target
	table is the failure mode we care about; row-by-row mismatches are
	caught later by the bulk_insert path.
	"""
	deps = _PARENT_DEPENDENCIES.get(source_doctype, [])
	missing: list[str] = []
	for target_lookup in deps:
		try:
			n = frappe.db.count(target_lookup)
		except Exception:
			n = 0
		if n == 0:
			# Distinguish "target table empty because nothing migrated yet"
			# from "no source rows reference this lookup at all". Cheap
			# heuristic: if the source-side equivalent has rows, this is a
			# real prereq miss.
			source_lookup = _crm_to_source_doctype(target_lookup)
			if source_lookup:
				try:
					src_n = frappe.db.count(source_lookup)
				except Exception:
					src_n = 0
				if src_n > 0:
					missing.append(target_lookup)

	if missing:
		return (
			f"Upstream lookups not yet migrated: {', '.join(missing)}. "
			f"Run the per-tab migration for those source doctypes first, "
			f"or use the top-level Run Migration button to migrate all."
		)
	return None


def _crm_to_source_doctype(crm_doctype: str) -> str | None:
	"""Reverse-lookup helper for _preflight_link_check.

	REVERSE_DOCTYPE_MAP is keyed by ERPNext source name and yields the CRM
	target name. We need the inverse: given a CRM target, what's its
	ERPNext source?
	"""
	for src, tgt in REVERSE_DOCTYPE_MAP.items():
		if tgt == crm_doctype:
			return src
	return None

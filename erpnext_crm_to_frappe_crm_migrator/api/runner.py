def _dedup_json_list(raw: object) -> object:
	"""Return `raw` with duplicate entries removed, preserving first-seen
	order. Non-list values (NULL, malformed JSON, empty string) pass
	through unchanged so the column ends up with whatever the database
	default produces.
	"""
	if not raw or not isinstance(raw, str):
		return raw
	import json

	try:
		decoded = json.loads(raw)
	except (json.JSONDecodeError, TypeError):
		return raw
	if not isinstance(decoded, list):
		return raw
	seen: set = set()
	deduped: list = []
	for item in decoded:
		key = item if isinstance(item, (str, int, float, bool)) else json.dumps(item, sort_keys=True)
		if key in seen:
			continue
		seen.add(key)
		deduped.append(item)
	if len(deduped) == len(decoded):
		return raw  # no change — keep the original encoding
	return json.dumps(deduped)


def _build_target_row(
	src_row: dict,
	src_to_tgt: dict,
	target_cols: list[str],
	target_doctype: str,
	source_doctype: str,
	lead_to_prospect: dict[str, str] | None = None,
	lead_to_company: dict[str, str] | None = None,
	name_target_col: str | None = None,
) -> tuple:
	"""Compute a tuple of values matching `target_cols` order for one row."""
	out: dict[str, object] = {}

	# 1. preserved meta — copied straight from source
	for f in PRESERVED_META_FIELDS:
		out[f] = src_row.get(f)

	# 1b. name-routing — registries that map `name → <target_col>` (e.g.
	# UTM Source.name → CRM Lead Source.source_name). Skips the locked
	# Field Map path because `name` is filtered there.
	if name_target_col and name_target_col in target_cols:
		out[name_target_col] = src_row.get("name")

	# 2. metadata caches — copied if source has them (target column membership
	# was already enforced when target_cols was built). `_assign`,
	# `_user_tags` and `_liked_by` are JSON lists that source data
	# sometimes accumulates duplicate entries in (e.g. the same user added
	# to _assign twice by separate code paths). The desk + the CRM
	# frontend both render those lists naively, so a duplicate entry
	# shows up as a doubled avatar / chip. Strip duplicates here
	# preserving first-seen order.
	for f in PRESERVED_META_CACHE_FIELDS:
		if f in target_cols:
			out[f] = _dedup_json_list(src_row.get(f))

	# 3. mapped fields — the locked map drives the renames. Dynamic
	# Link source fields are deliberately skipped here so they don't
	# fight other source fields that legitimately map to the same
	# target column (e.g. a custom field on Opportunity → CRM Deal
	# organization). Step 5 is the sole writer for dynamic-link
	# values.
	dynamic_sources = {src_field for (src_dt, src_field) in DYNAMIC_LINK_ROUTES if src_dt == source_doctype}
	for src, tgt in src_to_tgt.items():
		if src in dynamic_sources:
			continue
		if tgt not in target_cols:
			continue
		out[tgt] = src_row.get(src)

	# 4. naming_series default — we provided `name` explicitly, so this is
	# just here to satisfy NOT NULL on targets that have the column.
	if "naming_series" in target_cols and not out.get("naming_series"):
		out["naming_series"] = src_row.get("naming_series") or ""

	# 5. Dynamic-Link routing — write the source value into the column
	# chosen by the controller field (e.g. Opportunity's party_name
	# lands on CRM Deal.lead when opportunity_from='Lead' and on
	# CRM Deal.organization when ='Prospect'). The other rule columns
	# are left with whatever step 3 wrote — so a custom field that
	# maps to organization survives in the from='Lead' case.
	for (src_dt, src_field), rule in DYNAMIC_LINK_ROUTES.items():
		if src_dt != source_doctype:
			continue
		controller_value = src_row.get(rule["controller_field"])
		value = src_row.get(src_field)
		chosen = rule["routes"].get(controller_value, rule["default_target"])
		if chosen in target_cols and value:
			out[chosen] = value

	# 6. For Opportunity from=Lead: also populate CRM Deal.organization.
	# Prefer the Prospect that owns the Lead (Prospect.leads child rows).
	# Otherwise fall back to the Lead's own company_name (a CRM
	# Organization for which is lazy-created in _ensure_lead_company_orgs).
	# Without one or the other, the deal lands with organization=NULL and
	# the desk renders the title as "undefined" because CRM Deal's
	# title_field is `organization`.
	if (
		source_doctype == "Opportunity"
		and src_row.get("opportunity_from") == "Lead"
		and "organization" in target_cols
	):
		lead = src_row.get("party_name")
		owning = (lead_to_prospect or {}).get(lead) or (lead_to_company or {}).get(lead)
		if owning:
			out["organization"] = owning

	# 7. ERPNext-Customer tracker — when an Opportunity is
	# `opportunity_from='Customer'` the chunk loop stashes the original
	# Customer.name into `_erpnext_customer` before rewriting party_name
	# to the bridged Prospect. Carry it through to the target column.
	if "erpnext_customer" in target_cols and src_row.get("_erpnext_customer"):
		out["erpnext_customer"] = src_row["_erpnext_customer"]

	# Build the tuple in target_cols order. None for any column we didn't
	# populate — the database default takes over (typically NULL).
	return tuple(out.get(c) for c in target_cols)


def _load_field_map(source_doctype: str, target_doctype: str) -> list[tuple[str, str]]:
	"""Return [(source_field, target_field), ...] from the locked Field Map.

	Skips meta fields (handled separately by PRESERVED_META_FIELDS).
	"""
	fm = frappe.qb.DocType(FIELD_MAP_DOCTYPE)
	rows = (
		frappe.qb.from_(fm)
		.select(fm["source"], fm.target)
		.where((fm.s_doctype == source_doctype) & (fm.t_doctype == target_doctype))
	).run(as_dict=True)
	pairs: list[tuple[str, str]] = []
	for r in rows:
		if r["source"] in PRESERVED_META_FIELDS:
			continue
		pairs.append((r["source"], r["target"]))
	return pairs


def _column_exists(doctype: str, column: str) -> bool:
	"""Return True if `tab<doctype>` has a column named `column`."""
	try:
		cols = frappe.db.get_table_columns(doctype)
		return column in cols
	except Exception:
		return False


